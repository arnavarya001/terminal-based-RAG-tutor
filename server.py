import os
import sys
from typing import Optional, List, Dict
from pydantic import BaseModel, Field
from fastapi import FastAPI, HTTPException, status
from fastapi.middleware.cors import CORSMiddleware
import uvicorn

# Ensure the script directory is in sys.path for local module resolution
script_dir = os.path.dirname(os.path.abspath(__file__))
if script_dir not in sys.path:
    sys.path.insert(0, script_dir)

# Import existing RAG chain logic from ask.py without rewriting
from ask import create_rag_chain

# Initialize FastAPI application
app = FastAPI(
    title="LangChain RAG Chatbot API",
    description="FastAPI server wrapping the existing LangChain + Chroma RAG chain with CORS and conversation memory support.",
    version="1.0.0",
)

# Enable CORS so browser-based web applications can call this API without errors
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

# Initialize and load Chroma database and RAG chain once at startup
print("[server] Loading Chroma vector database and existing RAG chain...")
try:
    rag_chain, retriever = create_rag_chain(db_path="db")
    print("[server] RAG chain successfully loaded and ready to serve requests.")
except Exception as e:
    print(f"[server] Failed to initialize RAG chain: {e}", file=sys.stderr)
    raise

# Conversation memory store to retain chat context across requests
# Structure: { session_id: [{"role": "user"|"assistant", "content": "..."}, ...] }
conversation_memory: Dict[str, List[Dict[str, str]]] = {}


class QuestionRequest(BaseModel):
    question: Optional[str] = Field(
        None,
        description="The question to ask the RAG chatbot",
        json_schema_extra={"example": "What information is in the document?"},
    )
    prompt: Optional[str] = Field(
        None,
        description="Alternative alias for question",
        json_schema_extra={"example": "What information is in the document?"},
    )
    session_id: Optional[str] = Field(
        "default",
        description="Session identifier for tracking conversation memory across requests",
        json_schema_extra={"example": "session_1"},
    )

    def get_question_text(self) -> str:
        q = self.question or self.prompt
        if not q or not q.strip():
            raise ValueError("A non-empty 'question' string is required.")
        return q.strip()


class AnswerResponse(BaseModel):
    question: str = Field(..., description="The question asked")
    answer: str = Field(..., description="The answer generated by the RAG chain")
    session_id: Optional[str] = Field("default", description="Active session ID for conversation memory")


@app.get("/")
def root():
    """Health check and API overview."""
    return {
        "status": "online",
        "message": "LangChain Chroma RAG API is running.",
        "endpoints": {
            "ask_post": "POST /ask (JSON body: {'question': '...'})",
            "ask_get": "GET /ask?question=...",
            "history": "GET /history?session_id=...",
            "docs": "/docs",
        },
    }


@app.post("/ask", response_model=AnswerResponse)
def ask_endpoint(payload: QuestionRequest):
    """
    Exposes /ask endpoint:
    Takes a question, runs it through the existing RAG chain,
    records the exchange in conversation memory, and returns the answer as JSON.
    """
    try:
        question_text = payload.get_question_text()
    except ValueError as val_err:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=str(val_err),
        )

    session_id = payload.session_id or "default"

    try:
        # Run question through the existing RAG chain
        response = rag_chain.invoke(question_text)

        # Handle string or dictionary outputs
        if isinstance(response, dict):
            answer_text = response.get("answer") or response.get("output") or str(response)
        else:
            answer_text = str(response)

        # Track conversation memory
        if session_id not in conversation_memory:
            conversation_memory[session_id] = []

        conversation_memory[session_id].append({
            "role": "user",
            "content": question_text,
        })
        conversation_memory[session_id].append({
            "role": "assistant",
            "content": answer_text,
        })

        return AnswerResponse(
            question=question_text,
            answer=answer_text,
            session_id=session_id,
        )

    except HTTPException:
        raise
    except Exception as exc:
        err_msg = str(exc)
        if "429" in err_msg or "RESOURCE_EXHAUSTED" in err_msg:
            raise HTTPException(
                status_code=status.HTTP_429_TOO_MANY_REQUESTS,
                detail="Google Gemini API rate limit or quota exceeded. Please wait or check your quota in .env.",
            )
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Error executing RAG chain: {err_msg}",
        )


@app.get("/ask", response_model=AnswerResponse)
def ask_endpoint_get(question: str, session_id: Optional[str] = "default"):
    """GET convenience handler for /ask to allow quick testing from a browser URL bar."""
    return ask_endpoint(QuestionRequest(question=question, session_id=session_id))


@app.get("/history")
def get_history(session_id: Optional[str] = "default"):
    """Inspect stored conversation memory for a session."""
    return {
        "session_id": session_id,
        "history": conversation_memory.get(session_id, []),
    }


@app.delete("/history")
def clear_history(session_id: Optional[str] = "default"):
    """Clear stored conversation memory for a session."""
    if session_id in conversation_memory:
        conversation_memory[session_id] = []
    return {"status": "cleared", "session_id": session_id}


if __name__ == "__main__":
    port = int(os.getenv("PORT", 8000))
    print(f"Starting FastAPI server on http://0.0.0.0:{port}...")
    uvicorn.run("server:app", host="0.0.0.0", port=port, reload=True)
